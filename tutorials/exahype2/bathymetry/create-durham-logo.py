"""!

Create DurhamLogo.h and DurhamLogo.cpp for the tutorial 11_tsunami.ipynb

The script downloads the shield of Durham University and writes it as a C++
array of strings into the directory of this script: one string per row of
pixels, starting with the top row, with a 1 for each purple pixel and a 0
for each white one. The tutorial uses the array as depth map. The two
generated files are part of the repository, so the tutorial runs without
internet access. Rerun the script only if you want to change the depth map:

     python3 tutorials/exahype2/bathymetry/create-durham-logo.py

"""
import os
import urllib.request

import matplotlib.image

Here = os.path.dirname(os.path.abspath(__file__))

LogoURL = "https://www.topuniversities.com/sites/default/files/profiles/logos/durham-university_170_large.jpg"

Header = """// This file is part of the Peano project. For conditions of distribution and
// use, please see the copyright notice at www.peano-framework.org
//
// Generated by create-durham-logo.py. Do not edit.
#pragma once

namespace tutorials::exahype2::tsunami {{
  /**
   * Number of pixels per axis of DurhamLogo
   */
  constexpr int DurhamLogoSize = {size};

  /**
   * The shield of Durham University as depth map
   *
   * One string per row of pixels, starting with the top row of the image,
   * i.e. DurhamLogo[row][column]. A '1' marks a purple pixel, a '0' a white
   * one. The tutorial 11_tsunami.ipynb maps the image onto its domain and
   * uses it as depth map: the water is deeper where the logo is purple.
   *
   * Created from
   *
   *   {url}
   *
   * by create-durham-logo.py.
   */
  extern const char* const DurhamLogo[DurhamLogoSize];
}} // namespace tutorials::exahype2::tsunami
"""

Implementation = """// This file is part of the Peano project. For conditions of distribution and
// use, please see the copyright notice at www.peano-framework.org
//
// Generated by create-durham-logo.py. Do not edit.
#include "DurhamLogo.h"

const char* const tutorials::exahype2::tsunami::DurhamLogo[DurhamLogoSize] = {{
{rows}
}};
"""


if __name__ == "__main__":
    # The server rejects requests without a browser-like User-Agent
    request = urllib.request.Request(LogoURL, headers={"User-Agent": "Mozilla/5.0"})
    logo = matplotlib.image.imread(urllib.request.urlopen(request), format="jpg") / 255.0
    purple = logo.mean(axis=2) < 0.7
    assert purple.shape[0] == purple.shape[1], "We expect a square logo"

    rows = ",\n".join(
        '  "' + "".join("1" if pixel else "0" for pixel in row) + '"' for row in purple
    )
    with open(os.path.join(Here, "DurhamLogo.h"), "w") as f:
        f.write(Header.format(size=purple.shape[0], url=LogoURL))
    with open(os.path.join(Here, "DurhamLogo.cpp"), "w") as f:
        f.write(Implementation.format(rows=rows))
    print("wrote DurhamLogo.h and DurhamLogo.cpp into {}".format(Here))
