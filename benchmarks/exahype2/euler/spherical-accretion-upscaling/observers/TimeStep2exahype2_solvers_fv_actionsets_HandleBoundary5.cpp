void benchmarks::exahype2::euler::sphericalaccretionupscaling::observers::TimeStep2exahype2_solvers_fv_actionsets_HandleBoundary5::touchFaceFirstTime(
      const peano4::datamanagement::FaceMarker& marker,
      benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVQOld& fineGridFaceSelfSimilarInfallFVQOld,
      benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVQNew& fineGridFaceSelfSimilarInfallFVQNew,
      benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVQUpdate& fineGridFaceSelfSimilarInfallFVQUpdate,
      benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVFaceLabel& fineGridFaceSelfSimilarInfallFVFaceLabel,
      peano4::datamanagement::FaceEnumerator<benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVQOld> coarseGridFacesSelfSimilarInfallFVQOld,
      peano4::datamanagement::FaceEnumerator<benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVQNew> coarseGridFacesSelfSimilarInfallFVQNew,
      peano4::datamanagement::FaceEnumerator<benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVQUpdate> coarseGridFacesSelfSimilarInfallFVQUpdate,
      peano4::datamanagement::FaceEnumerator<benchmarks::exahype2::euler::sphericalaccretionupscaling::facedata::SelfSimilarInfallFVFaceLabel> coarseGridFacesSelfSimilarInfallFVFaceLabel,
      benchmarks::exahype2::euler::sphericalaccretionupscaling::celldata::SelfSimilarInfallFVQ& coarseGridCellSelfSimilarInfallFVQ,
      benchmarks::exahype2::euler::sphericalaccretionupscaling::celldata::SelfSimilarInfallFVCellLabel& coarseGridCellSelfSimilarInfallFVCellLabel) {

    if (
      not marker.willBeRefined() and repositories::InstanceOfSelfSimilarInfallFV.getSolverState()!=SelfSimilarInfallFV::SolverState::GridConstruction and (repositories::InstanceOfSelfSimilarInfallFV.getSolverState()==SelfSimilarInfallFV::SolverState::GridInitialisation or repositories::InstanceOfSelfSimilarInfallFV.getSolverState()==SelfSimilarInfallFV::SolverState::Primary or repositories::InstanceOfSelfSimilarInfallFV.getSolverState()==SelfSimilarInfallFV::SolverState::PrimaryAfterGridInitialisation)
      and
      not repositories::InstanceOfSelfSimilarInfallFV.PeriodicBC[marker.getSelectedFaceNumber()%Dimensions]
      and
      not marker.hasBeenRefined() 
      and 
      fineGridFaceSelfSimilarInfallFVFaceLabel.getBoundary()
    ) {
      logTraceInWith3Arguments( "touchFaceFirstTime(...)", fineGridFaceSelfSimilarInfallFVFaceLabel.toString(), (repositories::InstanceOfSelfSimilarInfallFV.PeriodicBC[marker.getSelectedFaceNumber()%Dimensions]), marker.toString() );
      ::exahype2::fv::applyBoundaryConditions(
        [&](
          const double * __restrict__                  Qinside,
          double * __restrict__                        Qoutside,
          const tarch::la::Vector<Dimensions,double>&  faceCentre,
          const tarch::la::Vector<Dimensions,double>&  volumeH,
          double                                       t,
          double                                       dt,
          int                                          normal
        ) -> void {
          repositories::InstanceOfSelfSimilarInfallFV.boundaryConditions( Qinside, Qoutside, faceCentre, volumeH, t, normal );
        },  
        marker.x(),
        marker.h(),
        fineGridFaceSelfSimilarInfallFVFaceLabel.getNewTimeStamp(marker.getSelectedFaceNumber()<Dimensions ? 1 : 0),
        repositories::InstanceOfSelfSimilarInfallFV.getMinTimeStepSize(),
        4,
        1,
        5+0,
        marker.getSelectedFaceNumber(),
        fineGridFaceSelfSimilarInfallFVQNew.value
      );
      ::exahype2::fv::applyBoundaryConditions(
        [&](
          const double * __restrict__                  Qinside,
          double * __restrict__                        Qoutside,
          const tarch::la::Vector<Dimensions,double>&  faceCentre,
          const tarch::la::Vector<Dimensions,double>&  volumeH,
          double                                       t,
          double                                       dt,
          int                                          normal
        ) -> void {
          repositories::InstanceOfSelfSimilarInfallFV.boundaryConditions( Qinside, Qoutside, faceCentre, volumeH, t, normal );
        },  
        marker.x(),
        marker.h(),
        fineGridFaceSelfSimilarInfallFVFaceLabel.getOldTimeStamp(marker.getSelectedFaceNumber()<Dimensions ? 1 : 0),
        repositories::InstanceOfSelfSimilarInfallFV.getMinTimeStepSize(),
        4,
        1,
        5+0,
        marker.getSelectedFaceNumber(),
        fineGridFaceSelfSimilarInfallFVQOld.value
      );
      
      bool isLeftEntryOutside = marker.getSelectedFaceNumber() < Dimensions;
      double innerTimeStamp;
      
      innerTimeStamp = fineGridFaceSelfSimilarInfallFVFaceLabel.getUpdatedTimeStamp( isLeftEntryOutside ? 1 : 0 );
      fineGridFaceSelfSimilarInfallFVFaceLabel.setUpdatedTimeStamp( isLeftEntryOutside ? 0 : 1, innerTimeStamp );
      
      innerTimeStamp = fineGridFaceSelfSimilarInfallFVFaceLabel.getNewTimeStamp( isLeftEntryOutside ? 1 : 0 );
      fineGridFaceSelfSimilarInfallFVFaceLabel.setNewTimeStamp( isLeftEntryOutside ? 0 : 1, innerTimeStamp );

      innerTimeStamp = fineGridFaceSelfSimilarInfallFVFaceLabel.getOldTimeStamp( isLeftEntryOutside ? 1 : 0 );
      fineGridFaceSelfSimilarInfallFVFaceLabel.setOldTimeStamp( isLeftEntryOutside ? 0 : 1, innerTimeStamp );

      logTraceOut( "touchFaceFirstTime(...)" );
    }
    else {
      logDebug( "touchFaceFirstTime(...)", "skip face " << marker.toString() );
    }
}


