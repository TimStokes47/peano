#include "peano4/datamanagement/FaceMarker.h"
#include "peano4/grid/GridTraversalEvent.h"
#include "peano4/grid/TraversalObserver.h"


namespace peano4 {
  namespace datamanagement {
    /**
     * Load the face data of one cell onto the call stack
     *
     * Face counterpart of loadVertexData(): Called by the generated observers
     * in loadCell(), once per face data type, it handles the @f$ 2d @f$ faces
     * of the cell. For each face, the routine takes the data from the stack
     * the event names (event.getFaceDataFrom()) and places it at the position
     * within the call stack block the event names (event.getFaceDataTo()):
     *
     * - If the face resides on an input stack and the data is to be loaded
     *   persistently, or if it resides on a temporary stack, the routine pops
     *   it from there.
     * - If the face is new (created or hanging) or the data is computed on,
     *   the routine creates new data.
     * - Otherwise, the data on the call stack is not initialised. Only the
     *   debug information is set.
     *
     * The routine used to be generated by peano4.api.output.Observer for
     * every data type. Its logic does not depend on the type though, so the
     * generated code now calls this function template.
     *
     * @tparam Data Face data type, i.e. the generated DaStGen or patch class.
     * @tparam StackMap Stack map holding the stacks of Data, e.g.
     *   peano4::maps::HierarchicalStackMap.
     * @tparam LoadStoreComputeFlag Functor mapping a FaceMarker onto a
     *   peano4::grid::LoadStoreComputeFlag. Typically a lambda forwarding to
     *   Data::loadStoreComputeFlag() with the data type's additional load and
     *   store arguments.
     *
     * @param stackMap The stacks of Data.
     * @param spacetreeId Tree on which the observer runs.
     * @param event The traversal event of loadCell().
     * @param faceMarker Marker of the cell's faces.
     * @param name Name of the data. Used for log messages only.
     * @param loadStoreComputeFlag See LoadStoreComputeFlag.
     */
    template <typename Data, typename StackMap, typename LoadStoreComputeFlag>
    void loadFaceData(
      StackMap&                               stackMap,
      int                                     spacetreeId,
      const peano4::grid::GridTraversalEvent& event,
      const FaceMarker&                       faceMarker,
      const char*                             name,
      LoadStoreComputeFlag                    loadStoreComputeFlag
    );

    /**
     * Store the face data of one cell from the call stack
     *
     * Counterpart of loadFaceData(), called by the generated observers in
     * storeCell(). For each of the @f$ 2d @f$ faces of the cell, the routine
     * takes the data from the call stack block and pushes it onto the stack
     * the event names (event.getFaceDataTo()) if this stack is a temporary
     * stack, or if it is an output stack and the data is to be stored
     * persistently. Otherwise, the data is dropped.
     *
     * @see loadFaceData() for the template arguments and parameters.
     */
    template <typename Data, typename StackMap, typename LoadStoreComputeFlag>
    void storeFaceData(
      StackMap&                               stackMap,
      int                                     spacetreeId,
      const peano4::grid::GridTraversalEvent& event,
      const FaceMarker&                       faceMarker,
      const char*                             name,
      LoadStoreComputeFlag                    loadStoreComputeFlag
    );

    /**
     * Send the data of one face
     *
     * Called by the generated observers in sendFace(). The routine copies
     * the data of the face at position within the call stack block onto
     * stack toStack if the data is stored persistently and if the data wants
     * to be sent or the domain is forked or joined.
     *
     * @tparam Send Functor mapping the data and a FaceMarker onto a bool:
     *   Does this data want to be sent? Typically a lambda forwarding to
     *   Data::send().
     *
     * @see loadFaceData() for the other template arguments and parameters.
     */
    template <
      typename Data,
      typename StackMap,
      typename LoadStoreComputeFlag,
      typename Send>
    void sendFaceData(
      StackMap&                                           stackMap,
      int                                                 spacetreeId,
      int                                                 position,
      int                                                 toStack,
      peano4::grid::TraversalObserver::SendReceiveContext context,
      const FaceMarker&                                   faceMarker,
      LoadStoreComputeFlag                                loadStoreComputeFlag,
      Send                                                send
    );

    /**
     * Receive the data of one face and merge it into the local data
     *
     * Called by the generated observers in receiveAndMergeFace(). If the
     * data of the face at position within the call stack block is loaded
     * persistently and wants to receive data, the routine pops the incoming
     * data from stack fromStack and merges it into the local data via
     * Data::merge().
     *
     * @tparam ReceiveAndMerge Functor mapping the data and a FaceMarker onto
     *   a bool: Does this data want to receive data? Typically a lambda
     *   forwarding to Data::receiveAndMerge().
     *
     * @see loadFaceData() for the other template arguments and parameters.
     */
    template <
      typename Data,
      typename StackMap,
      typename LoadStoreComputeFlag,
      typename ReceiveAndMerge>
    void receiveAndMergeFaceData(
      StackMap&                                           stackMap,
      int                                                 spacetreeId,
      int                                                 position,
      int                                                 fromStack,
      peano4::grid::TraversalObserver::SendReceiveContext context,
      const peano4::grid::GridTraversalEvent&             event,
      const FaceMarker&                                   faceMarker,
      LoadStoreComputeFlag                                loadStoreComputeFlag,
      ReceiveAndMerge                                     receiveAndMerge
    );
  } // namespace datamanagement
} // namespace peano4


