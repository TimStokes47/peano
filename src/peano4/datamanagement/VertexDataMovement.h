#pragma once


#include "peano4/datamanagement/VertexMarker.h"
#include "peano4/grid/GridTraversalEvent.h"
#include "peano4/grid/TraversalObserver.h"


namespace peano4 {
  namespace datamanagement {
    /**
     * Load the vertex data of one cell onto the call stack
     *
     * Called by the generated observers in loadCell(), once per vertex data
     * type. For each of the @f$ 2^d @f$ vertices of the cell, the routine
     * takes the data from the stack the event names (event.getVertexDataFrom())
     * and places it at the position within the call stack block the event
     * names (event.getVertexDataTo()):
     *
     * - If the vertex resides on an input stack and the data is to be
     *   loaded persistently, or if it resides on a temporary stack, the
     *   routine pops it from there.
     * - If the vertex is new (created or hanging) or the data is computed
     *   on, the routine creates new data.
     * - Otherwise, the data on the call stack is not initialised. Only the
     *   debug information is set.
     *
     * The routine used to be generated by peano4.api.output.Observer for
     * every data type. Its logic does not depend on the type though, so the
     * generated code now calls this function template.
     *
     * @tparam Data Vertex data type, i.e. the generated DaStGen or patch class.
     * @tparam StackMap Stack map holding the stacks of Data, e.g.
     *   peano4::maps::HierarchicalStackMap.
     * @tparam LoadStoreComputeFlag Functor mapping a VertexMarker onto a
     *   peano4::grid::LoadStoreComputeFlag. Typically a lambda forwarding to
     *   Data::loadStoreComputeFlag() with the data type's additional load and
     *   store arguments.
     *
     * @param stackMap The stacks of Data.
     * @param spacetreeId Tree on which the observer runs.
     * @param event The traversal event of loadCell().
     * @param vertexMarker Marker of the cell's vertices.
     * @param name Name of the data. Used for log messages only.
     * @param loadStoreComputeFlag See LoadStoreComputeFlag.
     */
    template <typename Data, typename StackMap, typename LoadStoreComputeFlag>
    void loadVertexData(
      StackMap&                               stackMap,
      int                                     spacetreeId,
      const peano4::grid::GridTraversalEvent& event,
      const VertexMarker&                     vertexMarker,
      const char*                             name,
      LoadStoreComputeFlag                    loadStoreComputeFlag
    );

    /**
     * Store the vertex data of one cell from the call stack
     *
     * Counterpart of loadVertexData(), called by the generated observers in
     * storeCell(). For each of the @f$ 2^d @f$ vertices of the cell, the
     * routine takes the data from the call stack block and pushes it onto
     * the stack the event names (event.getVertexDataTo()) if this stack is
     * a temporary stack, or if it is an output stack and the data is to be
     * stored persistently. Otherwise, the data is dropped.
     *
     * @see loadVertexData() for the template arguments and parameters.
     */
    template <typename Data, typename StackMap, typename LoadStoreComputeFlag>
    void storeVertexData(
      StackMap&                               stackMap,
      int                                     spacetreeId,
      const peano4::grid::GridTraversalEvent& event,
      const VertexMarker&                     vertexMarker,
      const char*                             name,
      LoadStoreComputeFlag                    loadStoreComputeFlag
    );

    /**
     * Send the data of one vertex
     *
     * Called by the generated observers in sendVertex(). The routine copies
     * the data of the vertex at position within the call stack block onto
     * stack toStack if the data is stored persistently and if the data wants
     * to be sent or the domain is forked or joined.
     *
     * @tparam Send Functor mapping the data and a VertexMarker onto a bool:
     *   Does this data want to be sent? Typically a lambda forwarding to
     *   Data::send().
     *
     * @see loadVertexData() for the other template arguments and parameters.
     */
    template <
      typename Data,
      typename StackMap,
      typename LoadStoreComputeFlag,
      typename Send>
    void sendVertexData(
      StackMap&                                           stackMap,
      int                                                 spacetreeId,
      int                                                 position,
      int                                                 toStack,
      peano4::grid::TraversalObserver::SendReceiveContext context,
      const VertexMarker&                                 vertexMarker,
      LoadStoreComputeFlag                                loadStoreComputeFlag,
      Send                                                send
    );

    /**
     * Receive the data of one vertex and merge it into the local data
     *
     * Called by the generated observers in receiveAndMergeVertex(). If the
     * data of the vertex at position within the call stack block is loaded
     * persistently and wants to receive data, the routine pops the incoming
     * data from stack fromStack and merges it into the local data via
     * Data::merge().
     *
     * @tparam ReceiveAndMerge Functor mapping the data and a VertexMarker
     *   onto a bool: Does this data want to receive data? Typically a lambda
     *   forwarding to Data::receiveAndMerge().
     *
     * @see loadVertexData() for the other template arguments and parameters.
     */
    template <
      typename Data,
      typename StackMap,
      typename LoadStoreComputeFlag,
      typename ReceiveAndMerge>
    void receiveAndMergeVertexData(
      StackMap&                                           stackMap,
      int                                                 spacetreeId,
      int                                                 position,
      int                                                 fromStack,
      peano4::grid::TraversalObserver::SendReceiveContext context,
      const peano4::grid::GridTraversalEvent&             event,
      const VertexMarker&                                 vertexMarker,
      LoadStoreComputeFlag                                loadStoreComputeFlag,
      ReceiveAndMerge                                     receiveAndMerge
    );
  } // namespace datamanagement
} // namespace peano4


