#include "peano4/datamanagement/CellMarker.h"
#include "peano4/grid/GridTraversalEvent.h"
#include "peano4/grid/TraversalObserver.h"


namespace peano4 {
  namespace datamanagement {
    /**
     * Load the data of one cell onto the call stack
     *
     * Cell counterpart of loadVertexData() and loadFaceData(): Called by the
     * generated observers in loadCell(), once per cell data type. The routine
     * pushes one entry onto the call stack:
     *
     * - If the cell's data resides on the stack the event names
     *   (event.getCellData()) and is to be loaded persistently, the routine
     *   pops it from there.
     * - If the cell is new or the data is computed on, the routine creates
     *   new data.
     * - Otherwise, the data on the call stack is not initialised. Only the
     *   debug information is set.
     *
     * The routine used to be generated by peano4.api.output.Observer for
     * every data type. Its logic does not depend on the type though, so the
     * generated code now calls this function template.
     *
     * @tparam Data Cell data type, i.e. the generated DaStGen or patch class.
     * @tparam StackMap Stack map holding the stacks of Data, e.g.
     *   peano4::maps::HierarchicalStackMap.
     * @tparam LoadStoreComputeFlag Functor mapping a CellMarker onto a
     *   peano4::grid::LoadStoreComputeFlag. Typically a lambda forwarding to
     *   Data::loadStoreComputeFlag() with the data type's additional load and
     *   store arguments.
     *
     * @param stackMap The stacks of Data.
     * @param spacetreeId Tree on which the observer runs.
     * @param event The traversal event of loadCell().
     * @param cellMarker Marker of the cell.
     * @param name Name of the data. Used for log messages only.
     * @param loadStoreComputeFlag See LoadStoreComputeFlag.
     *
     * ## Remote data
     *
     * If the traversal event tells us that the cell's source stack is
     * peano4::grid::TraversalObserver::NoData, the cell is not adjacent to
     * any local cell. The automaton hands out NoData for exactly these
     * entities. No user code ever sees them, as the observer masks all
     * events with isLocal(). We therefore do not construct a dummy data
     * object for them even if the flag asks for computeOnData(): that would
     * allocate and initialise (potentially large) data for nothing. The
     * slot on the call stack stays in its NoData state, just as for
     * entities whose flag is NoData.
     */
    template <typename Data, typename StackMap, typename LoadStoreComputeFlag>
    void loadCellData(
      StackMap&                               stackMap,
      int                                     spacetreeId,
      const peano4::grid::GridTraversalEvent& event,
      const CellMarker&                       cellMarker,
      const char*                             name,
      LoadStoreComputeFlag                    loadStoreComputeFlag
    );

    /**
     * Store the data of one cell from the call stack
     *
     * Counterpart of loadCellData(), called by the generated observers in
     * storeCell(). The routine pops the cell's entry from the call stack and
     * pushes it onto the stack the event names (event.getCellData()) if this
     * stack is a temporary stack, or if it is an output stack and the data is
     * to be stored persistently. Otherwise, the data is dropped.
     *
     * @see loadCellData() for the template arguments and parameters.
     */
    template <typename Data, typename StackMap, typename LoadStoreComputeFlag>
    void storeCellData(
      StackMap&                               stackMap,
      int                                     spacetreeId,
      const peano4::grid::GridTraversalEvent& event,
      const CellMarker&                       cellMarker,
      const char*                             name,
      LoadStoreComputeFlag                    loadStoreComputeFlag
    );

    /**
     * Send the data of the cell
     *
     * Called by the generated observers in sendCell(). The routine copies
     * the cell's data on top of the call stack onto stack toStack if the
     * data is stored persistently and if the data wants to be sent or the
     * domain is forked or joined.
     *
     * @tparam Send Functor mapping the data and a CellMarker onto a bool:
     *   Does this data want to be sent? Typically a lambda forwarding to
     *   Data::send().
     *
     * @see loadCellData() for the other template arguments and parameters.
     */
    template <
      typename Data,
      typename StackMap,
      typename LoadStoreComputeFlag,
      typename Send>
    void sendCellData(
      StackMap&                                           stackMap,
      int                                                 spacetreeId,
      int                                                 toStack,
      peano4::grid::TraversalObserver::SendReceiveContext context,
      const CellMarker&                                   cellMarker,
      LoadStoreComputeFlag                                loadStoreComputeFlag,
      Send                                                send
    );

    /**
     * Receive the data of the cell and merge it into the local data
     *
     * Called by the generated observers in receiveAndMergeCell(). If the
     * cell's data on top of the call stack is loaded persistently and wants
     * to receive data, the routine pops the incoming data from stack
     * fromStack and merges it into the local data via Data::merge().
     *
     * @tparam ReceiveAndMerge Functor mapping the data and a CellMarker onto
     *   a bool: Does this data want to receive data? Typically a lambda
     *   forwarding to Data::receiveAndMerge().
     *
     * @see loadCellData() for the other template arguments and parameters.
     */
    template <
      typename Data,
      typename StackMap,
      typename LoadStoreComputeFlag,
      typename ReceiveAndMerge>
    void receiveAndMergeCellData(
      StackMap&                                           stackMap,
      int                                                 spacetreeId,
      int                                                 fromStack,
      peano4::grid::TraversalObserver::SendReceiveContext context,
      const peano4::grid::GridTraversalEvent&             event,
      const CellMarker&                                   cellMarker,
      LoadStoreComputeFlag                                loadStoreComputeFlag,
      ReceiveAndMerge                                     receiveAndMerge
    );
  } // namespace datamanagement
} // namespace peano4


